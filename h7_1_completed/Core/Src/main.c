static uint8_t gyro_raw[BMI088_GYRO_RAW_SIZE];
static uint8_t usb_line[] = "GYRO_RAW: 00 00 00 00 00 00\r\n";

static uint8_t HexDigit(uint8_t value)
{
  value &= 0x0FU;
  return (value < 10U) ? (uint8_t)('0' + value)
                       : (uint8_t)('A' + value - 10U);
}

static void GyroRawToUsbLine(const uint8_t raw[BMI088_GYRO_RAW_SIZE])
{
  uint32_t i;

  for (i = 0U; i < BMI088_GYRO_RAW_SIZE; i++)
  {
    uint32_t position = 10U + (i * 3U);
    usb_line[position] = HexDigit(raw[i] >> 4U);
    usb_line[position + 1U] = HexDigit(raw[i]);
  }
}
